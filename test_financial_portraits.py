def make_allocator(portrait: Portrait) -> FinancialAllocator:
    settings = UserSettings(
        has_debts=bool(portrait.credits),
        employment_type=portrait.employment,
        critical_life=D(portrait.critical_life),
        household_reserve=D(portrait.household_reserve),
        average_income=D(portrait.average_income),
        income_type_tax_rates={name: D(rate) for name, rate in portrait.income_rates.items()},
        planned_taxes={name: D(value) for name, value in (portrait.planned_taxes or {}).items()},
        minimum_reserve_months=D(portrait.reserve_months),
        force_majeure_months=D(portrait.force_majeure_months),
        life_categories={name: D(value) for name, value in portrait.life_categories.items()},
        goals=[Goal(name, D(percent)) for name, percent in portrait.goals],
        credits=[Credit(name, D(balance), None, D(rate), D(payment)) for name, balance, rate, payment in portrait.credits],
    )
    return FinancialAllocator(settings)


class FinancialPortraitTests(unittest.TestCase):
    """Методы добавляются ниже динамически: один портрет — один отдельный тест."""


def run_portrait(test_case: unittest.TestCase, portrait: Portrait) -> None:
    allocator = make_allocator(portrait)
    test_case.assertEqual(allocator.settings.validate(), [])
    test_case.assertLessEqual(
        sum(allocator.settings.life_categories.values(), D("0")),
        allocator.settings.critical_life,
        portrait.title,
    )
    for income_type, amount_text in portrait.incomes:
        amount = D(amount_text)
        result = allocator.process_income(amount, income_type)
        expected_tax = amount * D(portrait.income_rates[income_type]) / D("100")
        test_case.assertEqual(result.tax, expected_tax, portrait.title)
        test_case.assertTrue(result.checks["ok"], portrait.title)
        test_case.assertLessEqual(abs(result.checks["difference"]), D("0.01"), portrait.title)
        test_case.assertTrue(all(value >= 0 for value in result.allocations.values()), portrait.title)
        test_case.assertIn(result.mode_after, range(1, 7), portrait.title)


for number, item in enumerate(PORTRAITS, 1):
    def scenario(self, portrait=item):
        run_portrait(self, portrait)

    scenario.__name__ = f"test_{number:02d}_{item.title.lower().replace(' ', '_').replace('-', '_')}"
    scenario.__doc__ = f"{item.title}, {item.age} лет, {item.location}: {item.circumstances}."
    setattr(FinancialPortraitTests, scenario.__name__, scenario)


if __name__ == "__main__":
    unittest.main()
