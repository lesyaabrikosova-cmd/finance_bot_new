"""Catalogue and presentation helpers for the optional financial archetype."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path


ASSETS_DIR = Path(__file__).resolve().parent / "assets" / "archetypes"


@dataclass(frozen=True)
class Archetype:
    slug: str
    emoji: str
    name: str
    image_path: Path
    everyday: str
    market: str

    @property
    def display_name(self) -> str:
        return f"{self.emoji} {self.name}"

    def caption(self) -> str:
        return (
            f"{self.emoji} <b>{self.name.upper()}</b>\n\n"
            f"<b>Быт</b>\n{self.everyday}\n\n"
            f"<b>Биржа</b>\n{self.market}"
        )


def _archetype(slug: str, emoji: str, name: str, everyday: str, market: str) -> Archetype:
    return Archetype(slug, emoji, name, ASSETS_DIR / f"{slug}.png", everyday, market)


